import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Router, type NextFunction, type Response, type Router as ExpressRouter } from "express";
import { z } from "zod";
import type { Prisma } from "../generated/prisma/client.js";
import { prisma } from "../lib/prisma.js";
import {
  authenticate,
  requireCapability,
  type AuthenticatedRequest,
} from "../middleware/auth.js";
import { validateQuery, validatedQuery } from "../middleware/validate.js";

export const systemConfigRouter: ExpressRouter = Router();

/**
 * GET /system/status — build and runtime facts (SYSTEM_ADMIN only).
 *
 * Note the mount: this router is mounted at `/system` (`app.ts:116`), not
 * `/admin/system`. The widget used to call the latter and got a 404 that the
 * hook quietly turned into "Unknown" for all three fields — the silent-zero
 * failure mode §13 forbids. `frontend/src/api/system.ts` now calls this path
 * through `apiClient`.
 */
/**
 * Where the build writes its stamp. The file is generated by `pnpm run build`
 * and is not in the repository.
 */
const BUILD_INFO_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "build-info.json",
);

systemConfigRouter.get(
  "/status",
  authenticate,
  requireCapability("SYSTEM_CONFIG"),
  async (req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> => {
    try {
      const gitCommitSha = process.env.VERCEL_GIT_COMMIT_SHA ?? process.env.GIT_COMMIT_SHA ?? "unknown";

      /**
       * The build stamp.
       *
       * "When was this deployed?" is the first question anyone asks when
       * something looks wrong, and the answer has to be *in the app*: the
       * revision (the commit) and the moment the build ran. The build writes
       * them to `build-info.json`; when it is absent — a local run, or a
       * deployment made before this existed — the field is `null` and the
       * screen says so, rather than inventing a date.
       */
      let builtAt: string | null = null;
      try {
        const stamp = JSON.parse(readFileSync(BUILD_INFO_PATH, "utf8")) as { builtAt?: string };
        builtAt = typeof stamp.builtAt === "string" ? stamp.builtAt : null;
      } catch {
        builtAt = null;
      }

      const status = {
        environment: process.env.NODE_ENV ?? "development",
        version: gitCommitSha.substring(0, 7),
        database: "connected",
        // How long this instance has been running. On a serverless platform a
        // cold start resets it, which is the honest answer: it is the uptime of
        // the thing serving the request, not of the deployment.
        uptime: Math.floor(process.uptime()),
        startedAt: new Date(Date.now() - Math.floor(process.uptime()) * 1000).toISOString(),
        builtAt,
      };

      res.status(200).json(status);
    } catch (err) {
      next(err);
    }
  },
);

/**
 * GET /system/events?limit= — recent account-level events (SYSTEM_ADMIN only).
 *
 * §10.4: this endpoint must never carry asset or audit activity. It used to
 * answer with `auditSession` rows relabelled `type: "AUDIT"` — each session's
 * scope, its operator and whether it completed — which handed the one role the
 * rules say sees zero asset data a running history of the college's audits.
 *
 * The source is now `AdminActionLog` (schema.prisma:243), the append-only
 * account log §0.4 requires, so every row is account-level *by construction* and
 * there is no asset-shaped filter left to get wrong. It is also the honest
 * answer to "what has this role been doing": nothing writes it yet — the account
 * flows (T5–T7) are what will — and an empty list is the true state until then,
 * not a placeholder.
 *
 * The response is a bare array, not `{ data }`: the only caller is
 * `frontend/src/api/system.ts`, and an envelope that one route in the codebase
 * uses is what made the consuming widget treat the object as a list.
 */

/**
 * `catch(10)` before `.default(10)`, and the clamp below, keep the behaviour the
 * route already had: `?limit=abc` and `?limit=999` mean "what you asked for,
 * within reason" rather than a 400 on a widget refresh. The caller is a
 * dashboard tile, and refusing to draw it over a stray query string would be a
 * worse failure than showing ten rows.
 */
const eventsQuerySchema = z.object({
  // The clamp lives in the route, not here: a `.max()` in the schema sends an
  // over-large page size to `.catch()` and answers with the *default* instead
  // of the largest page — so "?limit=9999" silently became 10.
  limit: z.coerce.number().int().catch(10).default(10),
  offset: z.coerce.number().int().catch(0).default(0),
  /** Filter by the action slug (`ACCOUNT_APPROVED`). */
  action: z.string().trim().min(1).optional(),
  /** A free-text search over the action and the person's name. */
  search: z.string().trim().min(1).optional(),
});
type EventsQuery = z.infer<typeof eventsQuerySchema>;

/**
 * `action` is stored as a slug (`ACCOUNT_APPROVED`). Sent as `type` unchanged —
 * greppable and stable — with a sentence carrying the person it happened to, so
 * a reader gets "who" without the widget having to join two fields itself.
 */
function describeAction(action: string, targetName: string | null): string {
  const readable = action.replaceAll("_", " ").toLowerCase();
  return targetName ? `${readable} — ${targetName}` : readable;
}

systemConfigRouter.get(
  "/events",
  authenticate,
  requireCapability("SYSTEM_CONFIG"),
  validateQuery(eventsQuerySchema),
  async (req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> => {
    try {
      const query = validatedQuery<EventsQuery>(req);
      const limit = Math.min(50, Math.max(1, query.limit));

      const where: Prisma.AdminActionLogWhereInput = {
        ...(query.action ? { action: query.action } : {}),
        ...(query.search
          ? {
              OR: [
                { action: { contains: query.search, mode: "insensitive" } },
                { targetUser: { is: { fullName: { contains: query.search, mode: "insensitive" } } } },
                { actor: { is: { fullName: { contains: query.search, mode: "insensitive" } } } },
              ],
            }
          : {}),
      };

      const [events, total] = await Promise.all([
        prisma.adminActionLog.findMany({
          where,
          take: limit,
          skip: query.offset,
          orderBy: { createdAt: "desc" },
          select: {
            id: true,
            action: true,
            createdAt: true,
            // The whole record: who did it, who it was about, what changed, and
            // the authority it was done under. A log row that says "account
            // approved" and nothing else is a title, not a record — the point of
            // an append-only log is that the detail can be read back.
            before: true,
            after: true,
            authorizedBy: true,
            authorizationRef: true,
            actor: { select: { fullName: true, email: true } },
            targetUser: { select: { fullName: true, email: true } },
            unit: { select: { name: true } },
          },
        }),
        prisma.adminActionLog.count({ where }),
      ]);

      res.status(200).json({
        events: events.map((event) => ({
          id: event.id,
          type: event.action,
          message: describeAction(event.action, event.targetUser?.fullName ?? null),
          timestamp: event.createdAt,
          actor: event.actor,
          target: event.targetUser,
          unit: event.unit?.name ?? null,
          before: event.before,
          after: event.after,
          authorizedBy: event.authorizedBy,
          authorizationRef: event.authorizationRef,
        })),
        total,
        limit,
        offset: query.offset,
      });
    } catch (err) {
      next(err);
    }
  },
);

/**
 * `GET /api/v1/system/statistics` — the shape of the college's register.
 *
 * The status page used to show three words ("production", a revision, and
 * "connected"), which answer "is it up?" and nothing else. An administrator
 * looking at a system wants to know how much it holds and how it is being
 * used: how many accounts and how many are waiting, what the decisions were,
 * what the assets look like, whether the requests are moving.
 *
 * Everything here is a **count** — no rows, no names, no values. It is a
 * summary of the system's shape, not a second copy of the register.
 */
systemConfigRouter.get(
  "/statistics",
  authenticate,
  requireCapability("SYSTEM_CONFIG"),
  async (_req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> => {
    try {
      const sixMonthsAgo = new Date();
      sixMonthsAgo.setMonth(sixMonthsAgo.getMonth() - 5);
      sixMonthsAgo.setDate(1);
      sixMonthsAgo.setHours(0, 0, 0, 0);

      const [
        accountsByStatus,
        accountsTotal,
        accountsCreated,
        decisions,
        itemsByStatus,
        itemsByDepartment,
        itemsTotal,
        requestsByStatus,
        requestsByType,
        auditsByState,
      ] = await Promise.all([
        prisma.user.groupBy({ by: ["accountStatus"], _count: { _all: true } }),
        prisma.user.count(),
        prisma.user.findMany({
          where: { createdAt: { gte: sixMonthsAgo } },
          select: { createdAt: true },
        }),
        prisma.adminActionLog.groupBy({ by: ["action"], _count: { _all: true } }),
        prisma.item.groupBy({ by: ["status"], _count: { _all: true } }),
        prisma.item.groupBy({ by: ["orgUnitId"], _count: { _all: true } }),
        prisma.item.count(),
        prisma.request.groupBy({ by: ["status"], _count: { _all: true } }),
        prisma.request.groupBy({ by: ["type"], _count: { _all: true } }),
        prisma.auditSession.groupBy({ by: ["sessionType"], _count: { _all: true } }),
      ]);

      // The departments the items belong to, by name, so the graph can be read.
      const departments = await prisma.orgUnit.findMany({
        where: { type: "DEPARTMENT" },
        select: { id: true, name: true },
      });
      const departmentName = new Map(departments.map((d) => [d.id, d.name]));

      // Accounts created per month, oldest first — the shape of the college's
      // own growth over the last six months.
      const perMonth = new Map<string, number>();
      for (let i = 0; i < 6; i += 1) {
        const month = new Date();
        month.setMonth(month.getMonth() - (5 - i));
        perMonth.set(month.toISOString().slice(0, 7), 0);
      }
      for (const account of accountsCreated) {
        const key = account.createdAt.toISOString().slice(0, 7);
        if (perMonth.has(key)) perMonth.set(key, (perMonth.get(key) ?? 0) + 1);
      }

      res.status(200).json({
        accounts: {
          total: accountsTotal,
          byStatus: Object.fromEntries(
            accountsByStatus.map((row) => [row.accountStatus, row._count._all]),
          ),
          perMonth: [...perMonth.entries()].map(([month, count]) => ({ month, count })),
        },
        decisions: decisions
          .map((row) => ({ action: row.action, count: row._count._all }))
          .sort((a, b) => b.count - a.count),
        items: {
          total: itemsTotal,
          byStatus: Object.fromEntries(itemsByStatus.map((row) => [row.status, row._count._all])),
          byDepartment: itemsByDepartment
            .map((row) => ({
              name: departmentName.get(row.orgUnitId ?? "") ?? "Unassigned",
              count: row._count._all,
            }))
            .sort((a, b) => b.count - a.count),
        },
        requests: {
          byStatus: Object.fromEntries(requestsByStatus.map((row) => [row.status, row._count._all])),
          byType: Object.fromEntries(requestsByType.map((row) => [row.type, row._count._all])),
        },
        audits: {
          byType: Object.fromEntries(auditsByState.map((row) => [row.sessionType, row._count._all])),
        },
      });
    } catch (err) {
      next(err);
    }
  },
);
